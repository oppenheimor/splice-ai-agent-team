/**
 * 将诊断结果格式化为 Prompt 可读的结构化文本
 * 注意：这里只提供结构化数据，不对数据做解读
 * （解读由 Prompt 中的「场景路由」和「诊断结果联动」规则自动完成）
 */
function formatDiagnosisContext(ctx: DiagnosisContext): string {
  const lines: string[] = [
    "```diagnosis",
    `经营类型代码: ${ctx.operatorCode}`,
    `经营类型: ${ctx.operatorTypeName}`,
    `AI落地阶段: ${ctx.aiAdoptionStage}`,
    `用户类型: ${ctx.userType}`,
    `人群分类: ${ctx.crowdType}`,
    `认知宽度: ${ctx.cognitiveWidth}`,
    `刚需方向: ${ctx.justNeed}`,
    "",
    "五维倾向:",
  ];

  for (const [dim, scores] of Object.entries(ctx.dimensionScores)) {
    const dimLabel = DIMENSION_LABELS[dim] || dim;
    lines.push(
      `  ${dimLabel}: 左${scores.left}% ↔ 右${scores.right}%`,
    );
  }

  if (ctx.blindSpots.length > 0) {
    lines.push("", `认知盲区: ${ctx.blindSpots.join("、")}`);
  }

  lines.push("```");

  return lines.join("\n");
}

/** 维度代码 → 中文标签 */
